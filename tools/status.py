#!/usr/bin/env python3
"""Regenerate STATUS.md from analysis/ and records/. Never edit STATUS.md by hand.

    python3 tools/status.py [--check]

--check exits 1 if STATUS.md is not what this would write (CI).
"""
import json
import sys
from collections import Counter, defaultdict

from model import LADDER, ROOT, config, load, read_tsv


def bar(done, total, width=20):
    n = round(width * done / total) if total else 0
    return "█" * n + "░" * (width - n)


def render():
    cfg = config()
    out = ["# Status", "", "_Generated by `tools/status.py` from `analysis/` and `records/`. Do not edit._", ""]
    for b in cfg["build"]:
        fns = load(b["id"])
        out += [f"## {b['id']} ({b['region']})", ""]
        if not fns:
            out += ["No analysis yet: run `python3 tools/match.py " + b["id"] + "`.", ""]
            continue
        s = json.loads((ROOT / "analysis" / b["id"] / "summary.json").read_text())
        m = s["measures"]
        same = "identical to the original" if s["relinked_identical"] else "**differs from the original**"
        out += [f"Relinked `main.dol`: SHA-1 `{s['relinked_sha1']}`, {same}. "
                f"objdiff: {m['matched_functions']:,} / {m['total_functions']:,} functions and "
                f"{int(m['matched_code']):,} / {int(m['total_code']):,} code bytes match "
                f"({m['matched_code_percent']:.2f}%); {m['complete_units']:,} / {m['total_units']:,} units are "
                f"complete (linked from source with data matching too: {m['complete_code_percent']:.2f}% of code). "
                f"Decomp at `{s['decomp_commit'][:7]}`.", ""]
        c = Counter(f.status for f in fns.values())
        total = len(fns)
        out += ["| status | functions | reached |", "|---|---:|---|"]
        for i, st in enumerate(LADDER):
            reached = sum(c[t] for t in LADDER[i:])
            out.append(f"| {st} | {c[st]:,} | {bar(reached, total)} {reached / total:.2%} |")
        out += ["", f"{total:,} functions. `integrated` = matches and compiled into the PC build (`port/`).", ""]
        subs = defaultdict(Counter)
        for f in fns.values():
            subs[f.subsystem][f.status] += 1
        out += ["### By subsystem", "", "| subsystem | functions | matches+ | in PC build |", "|---|---:|---:|---:|"]
        for name, cc in sorted(subs.items(), key=lambda kv: -sum(kv[1].values())):
            n = sum(cc.values())
            out.append(f"| `{name}` | {n:,} | {cc['matches'] + cc['integrated']:,} | {cc['integrated']:,} |")
        out.append("")
        left = [f for f in fns.values() if f.status not in ("matches", "integrated")]
        if left:
            out += ["### Not matching yet", "", "| va | function | status | match | source |", "|---|---|---|---:|---|"]
            for f in sorted(left, key=lambda f: f.va):
                out.append(f"| `{f.va}` | `{f.name}` | {f.status} | {f.fuzzy:g}% | {f.source or '—'} |")
            out.append("")
    bugs, patches = read_tsv(ROOT / "records" / "bugs.tsv"), read_tsv(ROOT / "records" / "patches.tsv")
    out += ["## Ledger", "", f"{len(bugs)} findings in `records/bugs.tsv`, {len(patches)} patches in "
            "`records/patches.tsv`.", ""]
    return "\n".join(out)


def main():
    text = render()
    path = ROOT / "STATUS.md"
    if "--check" in sys.argv:
        if not path.is_file() or path.read_text() != text:
            sys.exit("STATUS.md is out of date: run python3 tools/status.py")
        return
    path.write_text(text)
    print(text[:1500])


if __name__ == "__main__":
    main()
